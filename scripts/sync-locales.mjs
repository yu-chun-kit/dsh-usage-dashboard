import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const locales = ['en', 'zh-Hans', 'zh-Hant', 'ja']
const messages = {}
let keys
for (const locale of locales) {
  const data = JSON.parse(await readFile(new URL(`locales/${locale}.json`, root), 'utf8'))
  const current = Object.keys(data).sort()
  keys ??= current
  if (JSON.stringify(current) !== JSON.stringify(keys) || !Object.values(data).every(value => typeof value === 'string' && value.length > 0)) {
    throw new Error(`Incomplete translation dictionary: ${locale}`)
  }
  for (const key of keys) {
    const placeholders = value => (value.match(/\{\w+\}/g) ?? []).sort().join(',')
    if (locale !== 'en' && placeholders(data[key]) !== placeholders(messages.en[key])) throw new Error(`Translation placeholders differ: ${locale}.${key}`)
  }
  messages[locale] = data
}
const json = JSON.stringify(messages, null, 2)
const clientUrl = new URL('client.js', root)
const client = await readFile(clientUrl, 'utf8')
const begin = client.indexOf('    const TEXT =')
const end = client.indexOf('    const CRED_ROWS =', begin)
if (begin < 0 || end < 0) throw new Error('Browser translation block is missing')
const next = client.slice(0, begin) + '    // Generated by scripts/sync-locales.mjs from locales/*.json.\n    const TEXT = ' + json + '\n' + client.slice(end)
// The comment sits outside the replaceable block; keep repeated builds identical.
const previousComment = '    // Generated by scripts/sync-locales.mjs from locales/*.json.\n'
const normalized = next.replace(previousComment + previousComment, previousComment)
if (normalized !== client) await writeFile(clientUrl, normalized)
const generated = '// Generated by scripts/sync-locales.mjs. Edit locales/*.json.\nexport const messages = ' + json + '\nexport type UiLocale = keyof typeof messages\nexport type UiText = typeof messages.en\n'
const messagesUrl = new URL('src/client/messages.ts', root)
if (await readFile(messagesUrl, 'utf8').catch(() => '') !== generated) await writeFile(messagesUrl, generated)
